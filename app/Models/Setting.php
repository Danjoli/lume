     *
     * @var list<string>
     */
    protected $fillable = [

        /*
        |--------------------------------------------------------------------------
        | Loja
        |--------------------------------------------------------------------------
        */

        'store_name',

        'company_name',

        'cnpj',

        'description',

        /*
        |--------------------------------------------------------------------------
        | Contato
        |--------------------------------------------------------------------------
        */

        'email',

        'phone',

        'whatsapp',

        /*
        |--------------------------------------------------------------------------
        | Endereço
        |--------------------------------------------------------------------------
        */

        'cep',

        'street',

        'number',

        'complement',

        'neighborhood',

        'city',

        'state',

        /*
        |--------------------------------------------------------------------------
        | Redes Sociais
        |--------------------------------------------------------------------------
        */

        'facebook',

        'instagram',

        'linkedin',

        'youtube',

        'tiktok',

        'twitter',

        /*
        |--------------------------------------------------------------------------
        | Aparência
        |--------------------------------------------------------------------------
        */

        'logo',

        'favicon',

        /*
        |--------------------------------------------------------------------------
        | SEO
        |--------------------------------------------------------------------------
        */

        'meta_title',

        'meta_description',

        'keywords',

        /*
        |--------------------------------------------------------------------------
        | Pagamento
        |--------------------------------------------------------------------------
        */

        'payment_gateway',

        'pix_key',

        'currency',

        /*
        |--------------------------------------------------------------------------
        | Frete
        |--------------------------------------------------------------------------
        */

        'default_carrier',

        'origin_zipcode',

        /*
        |--------------------------------------------------------------------------
        | Email
        |--------------------------------------------------------------------------
        */

        'sender_name',

        'sender_email',

    ];

    /**
     * Conversões de atributos.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [

            'created_at' => 'datetime',

            'updated_at' => 'datetime',

        ];
    }

    /*
    |--------------------------------------------------------------------------
    | Helpers
    |--------------------------------------------------------------------------
    */

    /**
     * Retorna a configuração da loja.
     */
    public static function current(): self
    {
        return static::firstOrCreate(
            [],
            [
                'store_name' => 'Lume',
                'email' => 'contato@lume.com',
                'currency' => 'BRL',
            ]
        );
    }
}
